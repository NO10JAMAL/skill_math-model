#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
AI 风格与元数据脱敏审计工具 (AI Style & Metadata Audit)
用于检测数学建模论文 DOCX 中是否存在第三方脚本生成标记、零宽字符水印、高危戏剧化 AI 腔调以及句式节奏异常。
"""
import argparse
import json
import re
import statistics
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")

from docx import Document

# 高危戏剧化/夸张修辞禁词表（学术论文严禁出现的典型大模型套话）
BANNED_AI_WORDS = [
    "令人极大震惊", "令人大跌眼镜",
    "极具震撼力", "震撼",
    "发人深省",
    "无与伦比", "压倒性优势",
    "不可逆高危深渊", "深渊",
    "毁灭性失效", "毁灭性",
    "必要且充分的建模哲学", "建模哲学",
    "无可辩驳", "毫无疑问",
    "卓越的",
]

# 不可见字符 / 零宽字符水印列表
ZERO_WIDTH_CHARS = {
    "\u200b": "零宽空格 (Zero-width space)",
    "\u200c": "零宽非连接符 (Zero-width non-joiner)",
    "\u200d": "零宽连接符 (Zero-width joiner)",
    "\ufeff": "零宽无断空格 / BOM (Zero-width no-break space)",
    "\u2060": "单词连接符 (Word joiner)",
    "\u200e": "从左至右标记 (LRM)",
    "\u200f": "从右至左标记 (RLM)",
}

def audit_docx(docx_path: Path):
    path = Path(docx_path).resolve()
    if not path.is_file() or path.suffix.casefold() != ".docx":
        raise FileNotFoundError(f"DOCX 文件不存在: {path}")

    doc = Document(str(path))
    issues = []
    warnings = []

    # 1. 检查文档核心属性（元数据硬伤）
    props = doc.core_properties
    meta_info = {
        "author": props.author or "",
        "comments": props.comments or "",
        "last_modified_by": props.last_modified_by or "",
        "title": props.title or "",
        "subject": props.subject or "",
    }
    
    suspicious_meta = ["python-docx", "generated by", "docx-template", "apache poi"]
    for field, val in meta_info.items():
        val_lower = val.lower()
        for susp in suspicious_meta:
            if susp in val_lower:
                issues.append(f"元数据暴露脚本生成指纹: 属性 [{field}] 包含 '{val}'")
                break

    # 2. 收集正文及表格全部文本
    text_paras = [p.text for p in doc.paragraphs if p.text.strip()]
    full_text = "\n".join(text_paras)
    for table in doc.tables:
        for row in table.rows:
            full_text += "\n" + "\n".join(c.text.strip() for c in row.cells if c.text.strip())

    # 3. 检查零宽字符 / 隐形水印
    found_invisible = {}
    for zwc, desc in ZERO_WIDTH_CHARS.items():
        count = full_text.count(zwc)
        if count > 0:
            found_invisible[desc] = count
            issues.append(f"检测到潜在隐形水印/零宽字符: {desc} 出现 {count} 次")

    # 4. 扫描高危戏剧化 AI 腔调词汇（按词长降序消解，避免子串重复报警）
    banned_hits = {}
    scrubbed_text = full_text
    for word in sorted(BANNED_AI_WORDS, key=len, reverse=True):
        cnt = scrubbed_text.count(word)
        if cnt > 0:
            banned_hits[word] = cnt
            issues.append(f"命中高危 AI 情绪化/戏剧化套话: '{word}' 出现 {cnt} 次，建议替换为客观中立学术表达")
            scrubbed_text = scrubbed_text.replace(word, "")


    # 5. 突发度与句长方差（Burstiness）分析
    sentences = re.split(r"[。！？\n]", full_text)
    sentences = [s.strip() for s in sentences if len(s.strip()) > 3]
    lengths = [len(s) for s in sentences]

    mean_len = round(statistics.mean(lengths), 2) if lengths else 0
    std_dev = round(statistics.stdev(lengths), 2) if len(lengths) > 1 else 0
    min_len = min(lengths) if lengths else 0
    max_len = max(lengths) if lengths else 0

    if std_dev < 15 and len(lengths) > 50:
        warnings.append(f"句子长度标准差过小 (StdDev={std_dev}字)，句式过于匀速整齐，存在较强 AI 平滑特征")

    result = {
        "file": str(path),
        "metadata": meta_info,
        "metrics": {
            "sentence_count": len(sentences),
            "mean_sentence_length": mean_len,
            "length_stdev": std_dev,
            "min_length": min_len,
            "max_length": max_len,
        },
        "invisible_chars": found_invisible,
        "banned_word_hits": banned_hits,
        "issues": issues,
        "warnings": warnings,
        "passed": len(issues) == 0,
    }
    return result

def main():
    parser = argparse.ArgumentParser(description="数学建模论文 AI 风格与元数据脱敏审计")
    parser.add_argument("path", type=Path, help="待审计的 DOCX 论文路径")
    parser.add_argument("--json", action="store_true", help="以 JSON 格式输出审计报告")
    args = parser.parse_args()

    result = audit_docx(args.path)
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print("=" * 60)
        print("【数学建模论文 AI 风格与元数据审计报告】")
        print("=" * 60)
        print(f"目标文件: {result['file']}")
        print(f"审计状态: {'[PASS] 通过' if result['passed'] else '[FAIL] 未通过'}")
        print(f"句式突发度: 共 {result['metrics']['sentence_count']} 句，平均句长 {result['metrics']['mean_sentence_length']} 字，标准差 {result['metrics']['length_stdev']}")
        
        if result["issues"]:
            print("\n[!] 发现硬性阻断问题 (Issues):")
            for iss in result["issues"]:
                print(f"  - {iss}")
        else:
            print("\n[OK] 元数据无第三方脚本痕迹，未发现零宽字符水印，未命中高危 AI 情绪化套话。")
            
        if result["warnings"]:
            print("\n[?] 建议关注项 (Warnings):")
            for w in result["warnings"]:
                print(f"  - {w}")
        print("=" * 60)

    return 0 if result["passed"] else 1

if __name__ == "__main__":
    sys.exit(main())
